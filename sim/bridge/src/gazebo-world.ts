export function slug(model: string): string {
  return 'fuel_' + model.toLowerCase().replace(/ /g, '_');
}

/** The wrapper model of a Fuel model (models/<slug>/model.sdf). */
export function kindModel(k: Kind): string {
  const base = `${FUEL}${encodeURIComponent(k.model.toLowerCase())}/${k.version}/files`;
  const mesh = (submesh?: string) => `<mesh>
            <uri>${base}/meshes/${k.mesh}</uri>${submesh ? `
            <submesh><name>${submesh}</name></submesh>` : ''}
            <scale>${k.scale} ${k.scale} ${k.scale}</scale>
          </mesh>`;
  const visuals = k.visuals.map((v, i) => `      <visual name="visual_${i}">
        <geometry>
          ${mesh(v.submesh)}
        </geometry>${v.albedo ? `
        <material>
          <diffuse>1 1 1 1</diffuse>
          <specular>0.1 0.1 0.1 1</specular>${v.cutout ? `
          <double_sided>true</double_sided>` : ''}
          <pbr>
            <metal>
              <albedo_map>${base}/materials/textures/${v.albedo}</albedo_map>
              <metalness>0</metalness>
              <roughness>0.9</roughness>
            </metal>
          </pbr>
        </material>` : ''}
      </visual>`).join('\n');
  const collision = k.trunk
    ? `<cylinder><radius>${k.trunk[0]}</radius><length>${k.trunk[1]}</length></cylinder>`
    : mesh();
  const collisionPose = k.trunk ? `\n        <pose>0 0 ${k.trunk[1] / 2} 0 0 0</pose>` : '';
  return `<?xml version="1.0" ?>
<!-- Generated by sim/bridge/src/gazebo-world.ts: edit that, not this.
     ${k.model}: Open Robotics on Gazebo Fuel, CC-BY 4.0. -->
<sdf version="1.9">
  <model name="${slug(k.model)}">
    <static>true</static>
    <link name="link">
      <collision name="collision">${collisionPose}
        <geometry>
          ${collision}
        </geometry>
      </collision>
${visuals}
    </link>
  </model>
</sdf>
`;
}

export function kindConfig(k: Kind): string {
  return `<?xml version="1.0"?>
<model>
  <name>${slug(k.model)}</name>
  <version>1.0</version>
  <sdf version="1.9">model.sdf</sdf>
  <author><name>Open Robotics (Gazebo Fuel, CC-BY 4.0); wrapper generated by Disco FPV</name></author>
  <description>${k.model} from Gazebo Fuel with PBR materials for Gazebo Harmonic.</description>
</model>
`;
}

/** Deterministic pseudo-random numbers (mulberry32). */
export function rng(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export interface Placed {
  name: string;
  model: string;
  x: number;
  y: number;
  yaw: number;
}

/** Where the pilot holds the Disco before throwing it (metres). */
export const HAND_HEIGHT = 1.5;

/** Keeps the take-off area and its approach clear (metres). */
export const CLEAR_RADIUS = 60;

function clear(x: number, y: number): boolean {
  return Math.hypot(x, y) > CLEAR_RADIUS;
}

/** Every object of the world. */
export function layout(seed = 2318): Placed[] {
  const r = rng(seed);
  const out: Placed[] = [];
  const add = (model: string, x: number, y: number, yaw: number) => {
    if (!clear(x, y)) return;
    out.push({ name: `${model.toLowerCase().replace(/ /g, '_')}_${out.length}`, model, x, y, yaw });
  };

  // village: two rows of houses along an east-west road 250 m north
  const houses = ['House 1', 'House 2', 'House 3'] as const;
  for (let i = 0; i < 12; i++) {
    const x = -220 + i * 40 + (r() - 0.5) * 8;
    add(houses[i % 3]!, x, 250 + 18, Math.PI);
    add(houses[(i + 1) % 3]!, x + 10, 250 - 18, 0);
    if (i % 2 === 0) add('Lamp Post', x + 20, 250 + 7, 0);
  }
  add('Gas Station', 260, 245, 0);
  add('Office Building', -300, 290, Math.PI / 2);
  add('Water Tower', 150, 320, 0);

  // a wood south-west: dense pines
  for (let i = 0; i < 90; i++) {
    const a = r() * 2 * Math.PI;
    const d = Math.sqrt(r()) * 110;
    add('Pine Tree', -280 + d * Math.cos(a), -200 + d * Math.sin(a), r() * 2 * Math.PI);
  }
  // a hedgerow of oaks along the field's east side, a line to fly along
  for (let i = 0; i < 25; i++) {
    add('Oak tree', 180 + (r() - 0.5) * 4, -300 + i * 18 + (r() - 0.5) * 6, r() * 2 * Math.PI);
  }
  // scattered trees in the fields
  for (let i = 0; i < 40; i++) {
    const model = r() < 0.6 ? 'Oak tree' : 'Pine Tree';
    add(model, (r() - 0.5) * 900, (r() - 0.5) * 900, r() * 2 * Math.PI);
  }
  return out;
}

function include(p: Placed): string {
  return `    <include>
      <uri>model://${slug(p.model)}</uri>
      <name>${p.name}</name>
      <pose>${p.x.toFixed(1)} ${p.y.toFixed(1)} 0 0 0 ${p.yaw.toFixed(3)}</pose>
    </include>`;
}

/** A flat box drawn on the ground (road, mown strip): no collision. */
function slab(name: string, x: number, y: number, sx: number, sy: number, z: number, rgb: string): string {
  return `    <model name="${name}">
      <static>true</static>
      <pose>${x} ${y} ${z} 0 0 0</pose>
      <link name="link">
        <visual name="visual">
          <cast_shadows>false</cast_shadows>
          <geometry><box><size>${sx} ${sy} 0.02</size></box></geometry>
          <material>
            <ambient>${rgb} 1</ambient>
            <diffuse>${rgb} 1</diffuse>
            <specular>0.05 0.05 0.05 1</specular>
          </material>
        </visual>
      </link>
    </model>`;
}

export function world(lat: number, lon: number, elevation: number): string {
  const objects = layout().map(include).join('\n');
  return `<?xml version="1.0" ?>
<!-- Generated by sim/bridge/src/gazebo-world.ts: edit that, not this. -->
<sdf version="1.9">
  <world name="disco">
    <physics name="1ms" type="ignore">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-imu-system" name="gz::sim::systems::Imu"/>
    <!-- the hand launch (docker/gazebo/gz-helper.py) -->
    <plugin filename="gz-sim-apply-link-wrench-system" name="gz::sim::systems::ApplyLinkWrench"/>

    <scene>
      <ambient>0.6 0.6 0.6 1</ambient>
      <background>0.62 0.76 0.92 1</background>
      <sky></sky>
      <shadows>true</shadows>
    </scene>

    <spherical_coordinates>
      <latitude_deg>${lat}</latitude_deg>
      <longitude_deg>${lon}</longitude_deg>
      <elevation>${elevation}</elevation>
      <heading_deg>0</heading_deg>
      <surface_model>EARTH_WGS84</surface_model>
    </spherical_coordinates>

    <light type="directional" name="sun">
      <cast_shadows>true</cast_shadows>
      <pose>0 0 100 0 0 0</pose>
      <diffuse>0.9 0.9 0.85 1</diffuse>
      <specular>0.3 0.3 0.3 1</specular>
      <direction>-0.4 0.3 -0.85</direction>
    </light>

    <model name="ground">
      <static>true</static>
      <link name="link">
        <!-- an infinite plane holds the Disco (a thin box lets it sink);
             low friction, like its foam belly skidding on grass -->
        <collision name="collision">
          <geometry><plane><normal>0 0 1</normal><size>4000 4000</size></plane></geometry>
          <surface><friction><ode><mu>0.2</mu><mu2>0.2</mu2></ode></friction></surface>
        </collision>
        <visual name="visual">
          <cast_shadows>false</cast_shadows>
          <geometry><plane><normal>0 0 1</normal><size>4000 4000</size></plane></geometry>
          <material>
            <ambient>0.33 0.47 0.22 1</ambient>
            <diffuse>0.33 0.47 0.22 1</diffuse>
            <specular>0.05 0.05 0.05 1</specular>
          </material>
        </visual>
      </link>
    </model>
${slab('road', 0, 250, 800, 7, 0.005, '0.25 0.25 0.26')}
${slab('strip', 0, 0, 30, 220, 0.003, '0.42 0.56 0.28')}

${objects}

    <!-- the pilot's hand: holds the Disco level, nose north, 1.5 m up
         until the hand launch releases it (docker/gazebo/gz-helper.py);
         resting on its belly the Zephyr sits 17 degrees nose down and
         cannot take off by rolling -->
    <model name="hand">
      <pose>0 0 ${HAND_HEIGHT} 0 0 0</pose>
      <link name="link">
        <inertial><mass>1</mass></inertial>
      </link>
      <joint name="fixed" type="fixed">
        <parent>world</parent>
        <child>link</child>
      </joint>
    </model>
    <include>
      <uri>model://disco_zephyr</uri>
      <pose degrees="true">0 0 ${HAND_HEIGHT} 0 0 180</pose>
    </include>
  </world>
</sdf>
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { mkdirSync, writeFileSync } = await import('node:fs');
  const dir = process.argv[2] ?? '../gazebo';
  const [lat = 21.2665, lon = -157.8205, alt = 3] = (process.env.HOME_LOC ?? '').split(',').filter(Boolean).map(Number);
  mkdirSync(`${dir}/worlds`, { recursive: true });
  writeFileSync(`${dir}/worlds/disco.sdf`, world(lat, lon, alt));
  for (const k of KINDS) {
    mkdirSync(`${dir}/models/${slug(k.model)}`, { recursive: true });
    writeFileSync(`${dir}/models/${slug(k.model)}/model.sdf`, kindModel(k));
    writeFileSync(`${dir}/models/${slug(k.model)}/model.config`, kindConfig(k));
  }
}
