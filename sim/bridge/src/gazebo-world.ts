export function slug(model: string): string {
  return 'fuel_' + model.toLowerCase().replace(/ /g, '_');
}

/** The wrapper model of a Fuel model (models/<slug>/model.sdf). */
export function kindModel(k: Kind): string {
  const base = `${FUEL}${encodeURIComponent(k.model.toLowerCase())}/${k.version}/files`;
  const mesh = (submesh?: string) => `<mesh>
            <uri>${base}/meshes/${k.mesh}</uri>${submesh ? `
            <submesh><name>${submesh}</name></submesh>` : ''}
            <scale>${k.scale} ${k.scale} ${k.scale}</scale>
          </mesh>`;
  const visuals = k.visuals.map((v, i) => `      <visual name="visual_${i}">
        <geometry>
          ${mesh(v.submesh)}
        </geometry>${v.albedo ? `
        <material>
          <diffuse>1 1 1 1</diffuse>
          <specular>0.1 0.1 0.1 1</specular>${v.cutout ? `
          <double_sided>true</double_sided>` : ''}
          <pbr>
            <metal>
              <albedo_map>${base}/materials/textures/${v.albedo}</albedo_map>
              <metalness>0</metalness>
              <roughness>0.9</roughness>
            </metal>
          </pbr>
        </material>` : ''}
      </visual>`).join('\n');
  const collision = k.trunk
    ? `<cylinder><radius>${k.trunk[0]}</radius><length>${k.trunk[1]}</length></cylinder>`
    : mesh();
  const collisionPose = k.trunk ? `\n        <pose>0 0 ${k.trunk[1] / 2} 0 0 0</pose>` : '';
  return `<?xml version="1.0" ?>
<!-- Generated by sim/bridge/src/gazebo-world.ts: edit that, not this.
     ${k.model}: Open Robotics on Gazebo Fuel, CC-BY 4.0. -->
<sdf version="1.9">
  <model name="${slug(k.model)}">
    <static>true</static>
    <link name="link">
      <collision name="collision">${collisionPose}
        <geometry>
          ${collision}
        </geometry>
      </collision>
${visuals}
    </link>
  </model>
</sdf>
`;
}

