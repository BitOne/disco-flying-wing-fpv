const FUEL = 'https://fuel.gazebosim.org/1.0/openrobotics/models/';

/** A Fuel model's visual: a mesh (or one of its submeshes) and its texture. */
interface Visual {
  submesh?: string;
  albedo?: string;
  /** leaves: the texture's alpha cuts the shape out */
  cutout?: boolean;
}

/** The Fuel models of the world (Open Robotics, CC-BY 4.0) and their files. */
export interface Kind {
  model: string;
  version: number;
  mesh: string;
  scale: number;
  visuals: Visual[];
  /** collision: the mesh, or a trunk of this radius and height */
  trunk?: [number, number];
}

