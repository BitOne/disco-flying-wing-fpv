export function world(lat: number, lon: number, elevation: number): string {
  const objects = layout().map(include).join('\n');
  return `<?xml version="1.0" ?>
<!-- Generated by sim/bridge/src/gazebo-world.ts: edit that, not this. -->
<sdf version="1.9">
  <world name="disco">
    <physics name="1ms" type="ignore">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-imu-system" name="gz::sim::systems::Imu"/>
    <!-- the hand launch (docker/gazebo/gz-helper.py) -->
    <plugin filename="gz-sim-apply-link-wrench-system" name="gz::sim::systems::ApplyLinkWrench"/>

    <scene>
      <ambient>0.6 0.6 0.6 1</ambient>
      <background>0.62 0.76 0.92 1</background>
      <sky></sky>
      <shadows>true</shadows>
    </scene>

    <spherical_coordinates>
      <latitude_deg>${lat}</latitude_deg>
      <longitude_deg>${lon}</longitude_deg>
      <elevation>${elevation}</elevation>
      <heading_deg>0</heading_deg>
      <surface_model>EARTH_WGS84</surface_model>
    </spherical_coordinates>

    <light type="directional" name="sun">
      <cast_shadows>true</cast_shadows>
      <pose>0 0 100 0 0 0</pose>
      <diffuse>0.9 0.9 0.85 1</diffuse>
      <specular>0.3 0.3 0.3 1</specular>
      <direction>-0.4 0.3 -0.85</direction>
    </light>

    <include>
      <uri>model://disco_ground</uri>
    </include>

${objects}

    <!-- the pilot's hand: holds the Disco level, nose north, 1.5 m up
         until the hand launch releases it (docker/gazebo/gz-helper.py);
         resting on its belly the Zephyr sits 17 degrees nose down and
         cannot take off by rolling -->
    <model name="hand">
      <pose>0 0 ${HAND_HEIGHT} 0 0 0</pose>
      <link name="link">
        <inertial><mass>1</mass></inertial>
      </link>
      <joint name="fixed" type="fixed">
        <parent>world</parent>
        <child>link</child>
      </joint>
    </model>
    <include>
      <uri>model://disco_zephyr</uri>
      <pose degrees="true">0 0 ${HAND_HEIGHT} 0 0 180</pose>
    </include>
  </world>
</sdf>
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { mkdirSync, writeFileSync } = await import('node:fs');
  const dir = process.argv[2] ?? '../gazebo';
  const [lat = 21.2665, lon = -157.8205, alt = 3] = (process.env.HOME_LOC ?? '').split(',').filter(Boolean).map(Number);
  mkdirSync(`${dir}/worlds`, { recursive: true });
  writeFileSync(`${dir}/worlds/disco.sdf`, world(lat, lon, alt));
  mkdirSync(`${dir}/models/disco_ground/meshes`, { recursive: true });
  writeFileSync(`${dir}/models/disco_ground/model.sdf`, groundModel());
  writeFileSync(`${dir}/models/disco_ground/model.config`, groundConfig());
  for (const l of ground()) writeFileSync(`${dir}/models/disco_ground/meshes/${l.name}.obj`, layerObj(l));
  for (const k of KINDS) {
    mkdirSync(`${dir}/models/${slug(k.model)}`, { recursive: true });
    writeFileSync(`${dir}/models/${slug(k.model)}/model.sdf`, kindModel(k));
    writeFileSync(`${dir}/models/${slug(k.model)}/model.config`, kindConfig(k));
  }
}
